# import sklearn packages for feature engineering
from sklearn.preprocessing import PolynomialFeatures
from sklearn.linear_model import Lasso
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error, r2_score
import numpy as np
import pandas as pd

#add extra polynomial features equal to all combinations of powers to two features up to power 5
poly = PolynomialFeatures(degree=5, include_bias=False)
X_poly = poly.fit_transform(X)

feature_names = poly.get_feature_names_out(['x_1', 'x_2'])
table_data = {'Feature': feature_names}

c_options = [0.001, 0.01, 0.1, 1, 10, 100, 1000]

#train lasso regression models
lasso_models = {}
for C in c_options:
    alpha = 1 / (2 * C)
    lasso = Lasso(alpha=alpha, max_iter=10000)
    lasso.fit(X_poly, y)
    lasso_models[C] = lasso

    #formatting with pd
    formatted_coefs = [round(coef, 4) if abs(coef) > 1e-4 else 0.0 for coef in lasso.coef_]
    column_name = f"C = {C} (R²: {lasso.score(X_poly, y):.3f})"
    table_data[column_name] = formatted_coefs

    print(f"Trained C = {C} (alpha = {alpha:.4f}) -> Intercept: {lasso.intercept_:.4f}")

table_of_coef = pd.DataFrame(table_data)
