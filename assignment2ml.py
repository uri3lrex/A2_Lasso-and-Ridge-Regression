# cross validation to select c
from sklearn.model_selection import KFold
from sklearn.metrics import mean_squared_error
import numpy as np
import matplotlib.pyplot as plt

# 5-fold cross validation to plot mean and standard deviation of prediction vs C
C_values = np.logspace(-3, 5, 100)
kf = KFold(n_splits=5, shuffle=True, random_state=42)
mse_scores_lasso = []
std_scores_lasso = []

# loop and compare
for C in C_values:
    lasso = Lasso(alpha=1/(2*C), max_iter=10000)
    mse_fold = []
    for train_index, test_index in kf.split(X_poly):
        X_train, X_test = X_poly[train_index], X_poly[test_index]
        y_train, y_test = y[train_index], y[test_index]
        lasso.fit(X_train, y_train)
        y_pred = lasso.predict(X_test)
        mse_fold.append(mean_squared_error(y_test, y_pred))

    mse_scores_lasso.append(np.mean(mse_fold))
    std_scores_lasso.append(np.std(mse_fold))

# plot 
plt.figure(figsize=(10, 6))
plt.errorbar(C_values, mse_scores_lasso, yerr=std_scores_lasso, fmt='-o', capsize=5, elinewidth=1, markeredgewidth=1)
plt.xscale('log')
plt.xlabel('C')
plt.ylabel('Mean Squared Error')
plt.title('Cross-Validation Results (Lasso)')
